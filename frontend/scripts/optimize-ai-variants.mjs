// Picks, for every AI city page, the copy-variant "salt" that keeps the page as different as possible from the
// pages of the same country that were assigned before it. Existing assignments are never changed (page text stays
// stable between deployments); only new cities are optimised. Output: src/data/aiVariants.js
// Runs automatically before every build (package.json "prebuild"). Run `npm run variants -- --reset` to start over.
import { writeFileSync, existsSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join } from 'node:path'
import { COUNTRIES, citiesOf } from '../src/data/aiCities.js'
import { buildCityPage, pageText } from '../src/data/aiCallingContent.js'
import * as current from '../src/data/aiVariants.js'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const reset = process.argv.includes('--reset')
const TARGET = 0.36   // accept the first salt whose most-similar neighbour is below this
const TRIES = 24
const prev = reset ? {} : { ...current.SALTS }

const shingles = t => {
  const w = t.toLowerCase().replace(/\s+/g, ' ').trim().split(' ')
  const s = new Set()
  for (let i = 0; i + 5 <= w.length; i++) s.add(w.slice(i, i + 5).join(' '))
  return s
}
const sim = (a, b) => { let n = 0; for (const x of a) if (b.has(x)) n++; return n / (a.size + b.size - n) }

const out = {}
let worst = 0, changed = 0
for (const country of Object.keys(COUNTRIES)) {
  const accepted = []
  for (const c of citiesOf(country)) {
    const key = `${country}/${c.slug}`
    const score = salt => {
      const sh = shingles(pageText(buildCityPage(c, salt)))
      let m = 0
      for (const o of accepted) { const v = sim(sh, o); if (v > m) m = v; if (m > 0.9) break }
      return { sh, m }
    }
    let salt, best
    if (key in prev) { salt = prev[key]; best = score(salt) }
    else {
      changed++
      for (let t = 0; t < TRIES; t++) {
        const r = score(t)
        if (!best || r.m < best.m) { best = r; salt = t }
        if (r.m < TARGET) break
      }
    }
    out[key] = salt
    accepted.push(best.sh)
    if (best.m > worst) worst = best.m
  }
}

const body = `// Generated by scripts/optimize-ai-variants.mjs - do not edit by hand.\nexport const SALTS = ${JSON.stringify(out, null, 0).replace(/,"/g, ',\n  "').replace('{"', '{\n  "').replace(/\}$/, '\n}')}\n`
writeFileSync(join(root, 'src/data/aiVariants.js'), body)
console.log(`[variants] ${Object.keys(out).length} cities (${changed} newly optimised), highest similarity to an earlier page: ${(worst * 100).toFixed(0)}%`)
